import type { Summary } from '../api'

type Props =
  | { state: 'loading' }
  | { state: 'error'; message: string }
  | { state: 'done'; summary: Summary }

export function AiSummary(props: Props) {
  return (
    <section className="card ai-summary" aria-labelledby="ai-summary-title" aria-busy={props.state === 'loading'}>
      <div className="section-head">
        <h3 id="ai-summary-title">AI summary</h3>
        {props.state === 'done' && (
          <span className={`source-tag${props.summary.generated ? '' : ' source-fallback'}`}>
            {props.summary.generated ? `Generated by ${props.summary.model ?? 'Claude'}` : 'Automatic summary'}
          </span>
        )}
      </div>

      {props.state === 'loading' && (
        <div className="status-line" aria-live="polite">
          <span>&gt; GENERATING EXPLANATION…</span>
          <div className="scan-bar" />
        </div>
      )}

      {props.state === 'error' && <p className="muted">Could not get a summary: {props.message}</p>}

      {props.state === 'done' && (
        <>
          <p className="summary-text">{props.summary.text}</p>
          {!props.summary.generated && props.summary.note && (
            <p className="muted small">AI unavailable: {props.summary.note}</p>
          )}
          {props.summary.reasons.length > 0 && (
            <div className="reasons">
              <p className="eyebrow">Why</p>
              <ul>
                {props.summary.reasons.map((reason, i) => (
                  <li key={i}>
                    <span className={`badge badge-${reason.severity ?? 'info'}`}>
                      {reason.severity ?? 'info'}
                    </span>
                    <span>
                      <strong>{reason.check}</strong>
                      <span className="muted"> · {reason.category}</span>
                    </span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </>
      )}
    </section>
  )
}
